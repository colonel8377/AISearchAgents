"""Summarizer API routes - MVC View layer (only HTTP request/response handling)."""

from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Query

from src.shared.constant.enums import CoTMode
from src.shared.utils import get_logger
from ..common import get_api_key, summarizer_service
from ..schemas import (
    SummarizeRequest, SummaryResponse, AddTurnRequest
)

logger = get_logger(__name__)

router = APIRouter(prefix="/api/v1/agent", tags=["Summarizer"])


@router.post("/{agent_id}/summarizer/summarize", response_model=SummaryResponse)
async def summarize_conversation(
    agent_id: str,
    request: SummarizeRequest,
    _api_key: str = Depends(get_api_key)  # Authentication dependency (value not used)
):
    """
    Summarize conversation records using the Summarizer agent.

    This endpoint now focuses on user questions and handles long conversations
    by truncating and optimizing the input.

    Args:
        agent_id: The agent's unique identifier
        request: Summarization request with conversation records
        _api_key: Authentication dependency (value not used, required for auth check)

    Returns:
        Summary response with metadata about truncation
    """
    try:
        execution_mode = request.use_cot.value if isinstance(request.use_cot, CoTMode) else str(request.use_cot)
        result = summarizer_service.summarize_conversation(
            agent_id=agent_id,
            conversation_records=request.conversation_records,
            execution_mode=execution_mode,
            use_few_shots=request.use_few_shots
        )
        
        if "error" in result:
            logger.warning(f"Agent {agent_id} summarize error: {result['error']}")
            raise HTTPException(status_code=400, detail=result["error"])
        
        return SummaryResponse(**result)
    except ValueError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Failed to summarize conversation for agent {agent_id}: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"Failed to summarize conversation: {str(e)}")


