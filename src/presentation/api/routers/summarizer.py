@router.post("/{agent_id}/summarizer/conversation")
async def create_conversation(
    agent_id: str,
    conversation_id: Optional[str] = None,
    _api_key: str = Depends(get_api_key)  # Authentication dependency (value not used)
):
    """
    Create a new conversation for the Summarizer agent.
    
    A conversation contains multiple turns (user + assistant exchanges) and can have a summary.
    
    Args:
        agent_id: The agent's unique identifier
        conversation_id: Optional conversation ID. If None, auto-generate.
        _api_key: Authentication dependency (value not used, required for auth check)
    
    Returns:
        Conversation creation result with conversation_id
    """
    try:
        conv_id = summarizer_service.create_conversation(agent_id, conversation_id=conversation_id)
        return {
            "conversation_id": conv_id,
            "message": f"Conversation '{conv_id}' created successfully"
        }
    except ValueError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except Exception as e:
        logger.error(f"Failed to create conversation: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"Failed to create conversation: {str(e)}")


@router.post("/{agent_id}/summarizer/conversation/{conversation_id}/turn")
async def add_turn(
    agent_id: str,
    conversation_id: str,
    request: AddTurnRequest,
    _api_key: str = Depends(get_api_key)  # Authentication dependency (value not used)
):
    """
    Add a turn (user message + assistant response) to a conversation.
    
    Each turn represents one exchange: user asks a question, assistant responds.
    A conversation can contain multiple turns.
    
    Args:
        agent_id: The agent's unique identifier
        conversation_id: The conversation ID
        request: Request body with user_message and assistant_message
        _api_key: Authentication dependency (value not used, required for auth check)
    
    Returns:
        Success message with turn_index
    """
    try:
        result = summarizer_service.add_turn(
            agent_id=agent_id,
            conversation_id=conversation_id,
            user_message=request.user_message,
            assistant_message=request.assistant_message
        )
        
        if "error" in result:
            raise HTTPException(status_code=400, detail=result["error"])
        
        return result
    except ValueError as e:
        raise HTTPException(status_code=404, detail=str(e))
    except HTTPException:
        raise
    except Exception as e:
        logger.error(f"Failed to add turn: {e}", exc_info=True)
        raise HTTPException(status_code=500, detail=f"Failed to add turn: {str(e)}")


